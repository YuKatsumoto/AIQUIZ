def inject():
    with open(BANK_FILE, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    for subj, grades in NEW_QUIZZES.items():
        if subj not in data:
            data[subj] = {}
        for grade, quizzes in grades.items():
            if grade not in data[subj]:
                data[subj][grade] = []
            # Inject at the beginning
            data[subj][grade] = quizzes + data[subj][grade]
            
    with open(BANK_FILE, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        
    print("Grade 5 and 6 expansion completed.")

if __name__ == "__main__":
    inject()
