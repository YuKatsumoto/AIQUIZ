def load_json(path):
    if not os.path.exists(path): return {}
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def save_json(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def main():
    if not BANK_PATH.exists():
        print(f"エラー: {BANK_PATH} が見つかりません。")
        return

    bank_data = load_json(BANK_PATH)
    
    # 対象科目が存在しない場合は作成
    if "算数" not in bank_data:
        bank_data["算数"] = {}
    
    # 小6の算数を既存データから完全に削除し、エージェントが執筆した問題のみにする
    print(f"対象ファイル: {BANK_PATH.name}")
    print("既存の小6算数の問題を破棄し、完全にリニューアルします...")
    bank_data["算数"]["6"] = AGENT_MATH_GRADE_6
    
    save_json(BANK_PATH, bank_data)
    print(f"✅ 小6算数の問題（全20問）の注入・上書きが完了しました！")

if __name__ == "__main__":
    main()
