def merge():
    with open(os.path.abspath(BANK_PATH), "r", encoding="utf-8") as f:
        bank = json.load(f)

    added = 0
    skipped = 0
    per_slot = {}
    for subject, grades in NEW.items():
        if subject not in bank:
            bank[subject] = {}
        for grade, items in grades.items():
            if grade not in bank[subject]:
                bank[subject][grade] = []
            existing_q = set(it.get("q", "") for it in bank[subject][grade])
            slot_added = 0
            for it in items:
                if it["q"] in existing_q:
                    skipped += 1
                    continue
                bank[subject][grade].append(it)
                existing_q.add(it["q"])
                added += 1
                slot_added += 1
            per_slot["%s-G%s" % (subject, grade)] = slot_added

    with open(os.path.abspath(BANK_PATH), "w", encoding="utf-8") as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)

    total = 0
    for s, gd in bank.items():
        for g, arr in gd.items():
            total += len(arr)
    print("追加: %d問  スキップ(重複): %d問" % (added, skipped))
    print("スロット別追加:")
    for k in sorted(per_slot.keys()):
        print("  %s: +%d" % (k, per_slot[k]))
    print("バンク総数: %d問" % total)


if __name__ == "__main__":
    merge()
