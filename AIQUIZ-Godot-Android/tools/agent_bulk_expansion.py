def inject():
    if not BANK_PATH.exists():
        print(f"File not found: {BANK_PATH}")
        return
        
    with open(BANK_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    injected_count = 0
    for subj, grades in EXPANSION_QUIZZES.items():
        if subj not in data:
            data[subj] = {}
        for grade, quizzes in grades.items():
            if grade not in data[subj]:
                data[subj][grade] = []
            
            # Filter out existing by exact text match
            existing_questions = [q["q"] for q in data[subj][grade]]
            added_in_grade = 0
            
            for new_q in quizzes:
                if new_q["q"] not in existing_questions:
                    data[subj][grade].append(new_q)
                    added_in_grade += 1
                    injected_count += 1
            print(f"Added {added_in_grade} questions to {subj} Grade {grade}")
            
    with open(BANK_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        
    print(f"Successfully added {injected_count} new questions!")

if __name__ == "__main__":
    inject()
