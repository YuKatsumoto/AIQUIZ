def main():
    if not os.path.exists(OFFLINE_BANK_PATH):
        print("offline_bank.jsonが見つかりません。")
        return

    with open(OFFLINE_BANK_PATH, "r", encoding="utf-8") as f:
        try:
            bank = json.load(f)
        except json.JSONDecodeError:
            bank = {}

    added_count = 0
    
    # 既存のデータを更新・追加
    for subject, grades in new_quizzes.items():
        if subject not in bank:
            bank[subject] = {}
        for grade, questions in grades.items():
            if grade not in bank[subject]:
                bank[subject][grade] = []
            
            # 重複チェック（問題文で判定）
            existing_questions = {q["q"] for q in bank[subject][grade]}
            for q in questions:
                if q["q"] not in existing_questions:
                    bank[subject][grade].append(q)
                    added_count += 1

    with open(OFFLINE_BANK_PATH, "w", encoding="utf-8") as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)
    
    print(f"オフライン問題の補充が完了しました。新しく {added_count} 問を追加しました。")

if __name__ == "__main__":
    main()
